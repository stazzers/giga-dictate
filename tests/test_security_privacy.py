import os
import stat
import unittest
import numpy as np
from AppKit import NSPasteboard, NSStringPboardType
from giga_dictate.config import AppConfig, CONFIG_DIR, CONFIG_PATH
from giga_dictate.inserter import TextInserter, PBOARD_TYPE_TRANSIENT, PBOARD_TYPE_AUTOGEN
from giga_dictate.audio import AudioRecorder


class TestSecurityAndPrivacy(unittest.TestCase):
    def test_secure_config_permissions(self):
        """Ensure config directory is chmod 0700 and config.json is chmod 0600."""
        # Load user config without overwriting
        config = AppConfig.load()
        config.save()

        self.assertTrue(os.path.exists(CONFIG_DIR))
        dir_mode = stat.S_IMODE(os.stat(CONFIG_DIR).st_mode)
        self.assertEqual(dir_mode, 0o700, f"Expected config dir mode 0700, got {oct(dir_mode)}")

        self.assertTrue(os.path.exists(CONFIG_PATH))
        file_mode = stat.S_IMODE(os.stat(CONFIG_PATH).st_mode)
        self.assertEqual(file_mode, 0o600, f"Expected config file mode 0600, got {oct(file_mode)}")

    def test_clipboard_transient_anti_snoop(self):
        """Ensure insert_text tags pasteboard with TransientType & AutoGeneratedType."""
        inserter = TextInserter()
        secret_text = "Private confidential test phrase 12345"

        inserter.insert_text(secret_text, add_trailing_space=False, conceal_clipboard=True)

        pb = NSPasteboard.generalPasteboard()
        types = [str(t) for t in pb.types()]

        self.assertIn(NSStringPboardType, types)
        self.assertIn(PBOARD_TYPE_TRANSIENT, types, "Pasteboard missing TransientType privacy marker")
        self.assertIn(PBOARD_TYPE_AUTOGEN, types, "Pasteboard missing AutoGeneratedType privacy marker")

    def test_zero_network_during_audio_capture(self):
        """Ensure AudioRecorder works 100% in memory with no socket activity."""
        recorder = AudioRecorder()
        self.assertFalse(recorder.is_recording)
        self.assertFalse(hasattr(recorder, "socket"))
        self.assertFalse(hasattr(recorder, "session"))
        recorder.close()


if __name__ == "__main__":
    unittest.main()
