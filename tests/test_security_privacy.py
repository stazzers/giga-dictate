from tests.support import IsolatedTestCase
import os
import stat
import unittest
from AppKit import NSPasteboardTypeString
from giga_dictate.config import AppConfig
from giga_dictate import config as config_module
from giga_dictate.inserter import TextInserter, PBOARD_TYPE_TRANSIENT, PBOARD_TYPE_AUTOGEN
from giga_dictate.audio import AudioRecorder


class TestSecurityAndPrivacy(IsolatedTestCase):
    def test_secure_config_permissions(self):
        """Ensure config directory is chmod 0700 and config.json is chmod 0600."""
        # Save only within the isolated temporary config directory
        config = AppConfig.load()
        config.save()

        self.assertTrue(os.path.exists(config_module.CONFIG_DIR))
        dir_mode = stat.S_IMODE(os.stat(config_module.CONFIG_DIR).st_mode)
        self.assertEqual(dir_mode, 0o700, f"Expected config dir mode 0700, got {oct(dir_mode)}")

        self.assertTrue(os.path.exists(config_module.CONFIG_PATH))
        file_mode = stat.S_IMODE(os.stat(config_module.CONFIG_PATH).st_mode)
        self.assertEqual(file_mode, 0o600, f"Expected config file mode 0600, got {oct(file_mode)}")

    def test_clipboard_transient_anti_snoop(self):
        """Ensure insert_text tags pasteboard with TransientType & AutoGeneratedType."""
        inserter = TextInserter(clock=lambda: self.scheduler.now)
        secret_text = "Private confidential test phrase 12345"

        inserter.insert_text(secret_text, add_trailing_space=False, conceal_clipboard=True)
        self.scheduler.run_all()

        pb = self.pasteboard
        types = [str(t) for t in pb.types()]

        self.assertIn(NSPasteboardTypeString, types)
        self.assertIn(PBOARD_TYPE_TRANSIENT, types, "Pasteboard missing TransientType privacy marker")
        self.assertIn(PBOARD_TYPE_AUTOGEN, types, "Pasteboard missing AutoGeneratedType privacy marker")

    def test_zero_network_during_audio_capture(self):
        """Ensure AudioRecorder works 100% in memory with no socket activity."""
        recorder = AudioRecorder()
        self.assertFalse(recorder.is_recording)
        self.assertFalse(hasattr(recorder, "socket"))
        self.assertFalse(hasattr(recorder, "session"))
        recorder.close()

    def test_clipboard_erasure_after_insert(self):
        """Ensure that dictated text is erased/restored after insertion."""
        from unittest.mock import patch
        inserter = TextInserter(clock=lambda: self.scheduler.now)
        pb = self.pasteboard
        pb.clearContents()
        pb.setString_forType_("PREVIOUS_USER_COPY", NSPasteboardTypeString)

        # Insert new speech with restore_clipboard=True (mocking accessibility check and CGEventPost)
        with (
            patch.object(TextInserter, "is_accessibility_granted", return_value=True),
            patch("giga_dictate.inserter.CGEventPost"),
        ):
            inserter.insert_text("TEMPORARY_VOICE_TEXT", add_trailing_space=False, restore_clipboard=True)
            self.scheduler.run_all()

        # Spoken text MUST NOT remain in clipboard!
        current = pb.stringForType_(NSPasteboardTypeString)
        self.assertNotEqual(current, "TEMPORARY_VOICE_TEXT")
        self.assertEqual(current, "PREVIOUS_USER_COPY")


if __name__ == "__main__":
    unittest.main()
