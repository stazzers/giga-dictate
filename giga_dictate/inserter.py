"""Serialized, nonblocking clipboard transactions on the AppKit main loop."""
import logging
import time
from concurrent.futures import Future
from dataclasses import dataclass, field

from AppKit import NSURL, NSPasteboard, NSPasteboardItem, NSPasteboardTypeString, NSWorkspace
from ApplicationServices import (
    AXIsProcessTrusted, AXIsProcessTrustedWithOptions, kAXTrustedCheckOptionPrompt,
)
from PyObjCTools import AppHelper
from Quartz import (
    CGEventCreateKeyboardEvent, CGEventPost, CGEventSetFlags,
    CGEventSetIntegerValueField, CGEventSourceFlagsState,
    kCGEventFlagMaskAlternate, kCGEventFlagMaskCommand, kCGEventFlagMaskControl,
    kCGEventFlagMaskShift, kCGEventSourceStateHIDSystemState,
    kCGEventSourceUserData, kCGHIDEventTap,
)

from .events import SYNTHETIC_EVENT_TAG

logger = logging.getLogger("giga_dictate.inserter")
PBOARD_TYPE_TRANSIENT = "org.nspasteboard.TransientType"
PBOARD_TYPE_AUTOGEN = "org.nspasteboard.AutoGeneratedType"
PBOARD_TYPE_CONCEALED = "org.nspasteboard.ConcealedType"
_MODIFIERS = (kCGEventFlagMaskCommand | kCGEventFlagMaskShift
              | kCGEventFlagMaskControl | kCGEventFlagMaskAlternate)


@dataclass(frozen=True)
class InsertionResult:
    status: str  # event_posted, copied, error; event_posted is not delivery acknowledgement
    reason: str = ""

    @property
    def event_posted(self) -> bool:
        return self.status == "event_posted"

    def __bool__(self):
        return self.status != "error"


@dataclass
class _Operation:
    identifier: int
    future: Future
    text: str = field(repr=False)
    target_pid: int | None = None
    restore: bool = True
    conceal: bool = True
    delay: float = 0.03
    started: float = field(default_factory=time.monotonic)
    snapshot: list = field(default_factory=list, repr=False)
    change_count: int | None = None
    up_event: object = None
    down_posted: bool = False
    posted: bool = False


class TextInserter:
    """Call from the main thread. Completion includes clipboard cleanup.

    The returned Future contains an InsertionResult. No wait/sleep runs on the UI
    thread, and only one operation may own the clipboard at a time.
    """

    def __init__(self, pasteboard=None, schedule=None, clock=None):
        self._pasteboard = pasteboard if pasteboard is not None else NSPasteboard.generalPasteboard()
        self._schedule = schedule or AppHelper.callLater
        self._clock = clock or time.monotonic
        self._active = None
        self._generation = 0

    @staticmethod
    def is_accessibility_granted() -> bool:
        try:
            return bool(AXIsProcessTrusted())
        except Exception:
            logger.warning("accessibility_check_failed")
            return False

    @staticmethod
    def request_accessibility() -> None:
        try:
            AXIsProcessTrustedWithOptions({kAXTrustedCheckOptionPrompt: True})
            url = NSURL.URLWithString_(
                "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility"
            )
            if url:
                NSWorkspace.sharedWorkspace().openURL_(url)
        except Exception:
            logger.warning("accessibility_prompt_failed")

    def _front_pid(self):
        app = NSWorkspace.sharedWorkspace().frontmostApplication()
        return int(app.processIdentifier()) if app else None

    def _later(self, seconds, op, callback):
        def guarded():
            if self._active is not op:
                return
            try:
                callback(op)
            except Exception:
                logger.warning("insertion_callback_failed operation=%s", op.identifier)
                self._complete(op, "internal_error")
        try:
            self._schedule(seconds, guarded)
        except Exception:
            self._complete(op, "schedule_failed")

    def _snapshot(self):
        # Copy data, never retain live NSPasteboardItems owned by another process.
        # If a representation cannot be read, leave the original clipboard intact.
        saved = []
        for item in self._pasteboard.pasteboardItems() or []:
            clone = NSPasteboardItem.alloc().init()
            for kind in item.types():
                data = item.dataForType_(kind)
                if data is None or not clone.setData_forType_(data, kind):
                    raise RuntimeError("clipboard_snapshot_unavailable")
            saved.append(clone)
        return saved

    def _write(self, text, conceal):
        self._pasteboard.clearContents()
        if not self._pasteboard.setString_forType_(text, NSPasteboardTypeString):
            raise RuntimeError("clipboard_write_failed")
        if conceal:
            for kind in (PBOARD_TYPE_TRANSIENT, PBOARD_TYPE_AUTOGEN, PBOARD_TYPE_CONCEALED):
                if not self._pasteboard.setString_forType_("", kind):
                    raise RuntimeError("clipboard_marker_failed")

    def insert_text(self, text, add_trailing_space=True, restore_clipboard=False,
                    conceal_clipboard=True, delay=0.03) -> Future:
        future = Future()
        if self._active is not None or not text:
            future.set_result(InsertionResult("error", "busy" if self._active else "empty_text"))
            return future
        self._generation += 1
        op = _Operation(self._generation, future, text,
                        restore=restore_clipboard, conceal=conceal_clipboard,
                        delay=max(0.0, float(delay)), started=self._clock())
        if add_trailing_space and not op.text.endswith(" "):
            op.text += " "
        self._active = op
        try:
            op.target_pid = self._front_pid()
            if op.target_pid is None:
                self._complete(op, "no_target")
            elif not self.is_accessibility_granted():
                self._complete(op, "accessibility_denied")
            else:
                self._later(0.0, op, self._wait_modifiers)
        except Exception:
            self._complete(op, "prepare_failed")
        return future

    def _wait_modifiers(self, op):
        if self._front_pid() != op.target_pid:
            self._complete(op, "target_changed")
            return
        if CGEventSourceFlagsState(kCGEventSourceStateHIDSystemState) & _MODIFIERS:
            if self._clock() - op.started >= 1.0:
                self._complete(op, "modifiers_held")
            else:
                self._later(0.02, op, self._wait_modifiers)
            return
        snapshot_count = self._pasteboard.changeCount()
        try:
            op.snapshot = self._snapshot()
        except Exception:
            self._complete(op, "clipboard_snapshot_failed")
            return
        # Prepare both events before replacing anything in the clipboard.
        down = CGEventCreateKeyboardEvent(None, 9, True)
        op.up_event = CGEventCreateKeyboardEvent(None, 9, False)
        if down is None or op.up_event is None:
            self._complete(op, "event_creation_failed")
            return
        for event in (down, op.up_event):
            CGEventSetFlags(event, kCGEventFlagMaskCommand)
            CGEventSetIntegerValueField(event, kCGEventSourceUserData, SYNTHETIC_EVENT_TAG)
        if self._pasteboard.changeCount() != snapshot_count:
            self._complete(op, "clipboard_changed")
            return
        try:
            self._write(op.text, op.conceal)
        except Exception:
            op.change_count = self._pasteboard.changeCount()
            self._complete(op, "clipboard_write_failed")
            return
        op.change_count = self._pasteboard.changeCount()
        self._later(op.delay, op, lambda current: self._post_down(current, down))

    def _post_down(self, op, down):
        if self._front_pid() != op.target_pid:
            self._complete(op, "target_changed")
            return
        if self._pasteboard.changeCount() != op.change_count:
            self._complete(op, "clipboard_changed")
            return
        if CGEventSourceFlagsState(kCGEventSourceStateHIDSystemState) & _MODIFIERS:
            self._complete(op, "modifiers_held")
            return
        if not self.is_accessibility_granted():
            self._complete(op, "accessibility_denied")
            return
        CGEventPost(kCGHIDEventTap, down)
        op.down_posted = True
        self._later(0.015, op, self._post_up)

    def _post_up(self, op):
        CGEventPost(kCGHIDEventTap, op.up_event)
        op.down_posted = False
        op.posted = True
        logger.info("paste_event_posted operation=%s elapsed_ms=%.1f",
                    op.identifier, (self._clock() - op.started) * 1000)
        # The target application reads the pasteboard asynchronously.
        self._later(0.75, op, self._complete)

    def _complete(self, op, reason=""):
        if self._active is not op:
            return
        if op.down_posted:
            try:
                CGEventPost(kCGHIDEventTap, op.up_event)
            except Exception:
                pass
            op.down_posted = False
        try:
            if op.change_count is not None and (op.restore or reason):
                if self._pasteboard.changeCount() == op.change_count:
                    self._pasteboard.clearContents()
                    if op.snapshot and not self._pasteboard.writeObjects_(op.snapshot):
                        reason = reason or "clipboard_restore_failed"
                    logger.info("clipboard_restored operation=%s", op.identifier)
                else:
                    logger.info("clipboard_restore_skipped operation=%s reason=ownership_changed", op.identifier)
        except Exception:
            reason = reason or "clipboard_restore_failed"
        result = InsertionResult("error", reason) if reason else InsertionResult("event_posted")
        self._active = None
        op.text = ""
        op.snapshot = []
        if not op.future.done():
            op.future.set_result(result)
        if reason:
            logger.warning("insertion_failed operation=%s reason=%s", op.identifier, reason)

    def copy_text(self, text, conceal_clipboard=True) -> InsertionResult:
        if self._active:
            return InsertionResult("error", "busy")
        if not text:
            return InsertionResult("error", "empty_text")
        try:
            self._write(text, conceal_clipboard)
            return InsertionResult("copied")
        except Exception:
            return InsertionResult("error", "clipboard_write_failed")

    def cancel_pending(self):
        if self._active:
            self._complete(self._active, "cancelled")
