import logging
import os
import threading
import time
from typing import Optional
from AppKit import NSPasteboard, NSStringPboardType, NSURL, NSWorkspace
from ApplicationServices import (
    AXIsProcessTrusted,
    AXIsProcessTrustedWithOptions,
    kAXTrustedCheckOptionPrompt,
)
from Quartz import (
    CGEventCreateKeyboardEvent,
    CGEventPost,
    CGEventSetFlags,
    kCGEventFlagMaskCommand,
    kCGHIDEventTap,
)

logger = logging.getLogger("giga_dictate.inserter")


# Privacy types recognized by macOS clipboard history tools and iCloud Universal Clipboard
PBOARD_TYPE_TRANSIENT = "org.nspasteboard.TransientType"
PBOARD_TYPE_AUTOGEN = "org.nspasteboard.AutoGeneratedType"
PBOARD_TYPE_CONCEALED = "org.nspasteboard.ConcealedType"


class TextInserter:
    """Inserts transcribed text at current macOS cursor position via clipboard paste (Cmd+V)."""

    def __init__(self):
        self._pasteboard = NSPasteboard.generalPasteboard()

    @staticmethod
    def is_accessibility_granted() -> bool:
        """Returns True if Accessibility permissions are granted."""
        try:
            return bool(AXIsProcessTrusted())
        except Exception as e:
            logger.error(f"Error checking Accessibility: {e}")
            return False

    @staticmethod
    def request_accessibility() -> None:
        """Triggers the macOS Accessibility permission prompt and opens System Settings."""
        try:
            options = {kAXTrustedCheckOptionPrompt: True}
            AXIsProcessTrustedWithOptions(options)
        except Exception as e:
            logger.error(f"Failed to prompt for Accessibility: {e}")

        # Open System Settings directly to Accessibility panel via native Cocoa NSWorkspace
        try:
            url = NSURL.URLWithString_("x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility")
            if url:
                NSWorkspace.sharedWorkspace().openURL_(url)
        except Exception as e:
            logger.error(f"Failed to open System Settings: {e}")
        except Exception as e:
            logger.error(f"Failed to open System Settings: {e}")

    def insert_text(
        self,
        text: str,
        add_trailing_space: bool = True,
        restore_clipboard: bool = False,
        conceal_clipboard: bool = True,
        delay: float = 0.03,
    ) -> bool:
        """
        Pastes text at current cursor location.
        Returns True if Cmd+V event was posted, False otherwise.
        """
        if not text:
            return False

        if add_trailing_space and not text.endswith(" "):
            text += " "

        old_clipboard: Optional[str] = None
        if restore_clipboard:
            try:
                old_clipboard = self._pasteboard.stringForType_(NSStringPboardType)
            except Exception:
                old_clipboard = None

        # 1. Put transcribed text into clipboard with anti-snoop privacy tags
        try:
            self._pasteboard.clearContents()
            self._pasteboard.setString_forType_(text, NSStringPboardType)
            if conceal_clipboard:
                # Mark as transient and auto-generated to prevent clipboard history capture & iCloud cloud-sync
                self._pasteboard.setString_forType_("", PBOARD_TYPE_TRANSIENT)
                self._pasteboard.setString_forType_("", PBOARD_TYPE_AUTOGEN)
        except Exception as e:
            logger.error(f"Failed to copy to pasteboard: {e}")
            return False

        # 2. Check accessibility permissions
        has_permission = self.is_accessibility_granted()
        if not has_permission:
            logger.warning(
                "Accessibility permission not granted. Text copied to clipboard, but auto-paste cannot simulate Cmd+V."
            )
            return False

        # 3. Simulate Cmd+V keystroke (Keycode 9 = 'v' on standard Mac keyboard layout)
        time.sleep(delay)
        try:
            # Key Down (Cmd + V)
            v_code = 9
            down_event = CGEventCreateKeyboardEvent(None, v_code, True)
            CGEventSetFlags(down_event, kCGEventFlagMaskCommand)
            CGEventPost(kCGHIDEventTap, down_event)

            time.sleep(0.015)

            # Key Up (Cmd + V)
            up_event = CGEventCreateKeyboardEvent(None, v_code, False)
            CGEventSetFlags(up_event, kCGEventFlagMaskCommand)
            CGEventPost(kCGHIDEventTap, up_event)
        except Exception as e:
            logger.error(f"Failed to post CGEvent: {e}")
            return False

        # 4. Optional restore clipboard after application consumed it
        if restore_clipboard and old_clipboard is not None:

            def _restore():
                time.sleep(0.5)
                try:
                    self._pasteboard.clearContents()
                    self._pasteboard.setString_forType_(old_clipboard, NSStringPboardType)
                except Exception as e:
                    logger.debug(f"Failed to restore clipboard: {e}")

            threading.Thread(target=_restore, daemon=True).start()

        return True
